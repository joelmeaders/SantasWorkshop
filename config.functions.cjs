const { writeFile } = require('node:fs/promises');
const path = require('node:path');
const { loadEnvFiles } = require('./scripts/env-loader.cjs');

const FUNCTION_PROJECT_IDS = {
	test: 'santas-workshop-test',
	prod: 'santas-workshop-193b5',
};

const REQUIRED_FUNCTION_ENV_KEYS = [
	'AWS_ACCESS_KEY_ID',
	'AWS_SECRET_ACCESS_KEY',
	'ADMIN_BOOTSTRAP_PASSWORD',
	'SANTASHOP_PROGRAM_YEAR',
	'SANTASHOP_TIME_ZONE',
	'SANTASHOP_TIME_OFFSET',
	'SANTASHOP_DEFAULT_MAX_SLOTS',
	'FIRESTORE_BACKUP_BUCKET',
	'SES_REGION',
	'REGISTRATION_EMAIL_TEMPLATE',
	'REMINDER_EMAIL_TEMPLATE',
	'SANTASHOP_EVENT_DISPLAY_NAME',
	'REGISTRATION_EMAIL_SOURCE',
	'REGISTRATION_EMAIL_RETURN_PATH',
	'SCHEDULED_FIRESTORE_BACKUP',
	'SCHEDULED_DATETIME_SLOT_COUNTERS',
	'SCHEDULED_REGISTRATION_STATS',
	'SCHEDULED_USER_STATS',
	'SCHEDULED_CHECKIN_STATS',
];

const OPTIONAL_FUNCTION_ENV_KEYS = [
	'ADMIN_UIDS',
	'SANTASHOP_SHOP_DAYS',
	'REMINDER_EMAIL_SENDING_STALE_MINUTES',
	'AWS_REGION',
];

const ALL_FUNCTION_ENV_KEYS = [
	...REQUIRED_FUNCTION_ENV_KEYS,
	...OPTIONAL_FUNCTION_ENV_KEYS,
];

const loadLocalEnvFiles = () => {
	loadEnvFiles([
		path.resolve(process.cwd(), '.env'),
		path.resolve(__dirname, '.env'),
	]);
};

const parseMode = (value) => {
	if (!value || value === 'prod' || value === 'production') {
		return 'prod';
	}

	if (
		value === 'test' ||
		value === 'qa' ||
		value === 'dev' ||
		value === 'development'
	) {
		return 'test';
	}

	throw new Error(
		'Expected Functions config mode to be one of: test, qa, dev, development, prod, production.',
	);
};

const getModePrefix = (mode) => (mode === 'test' ? 'TEST' : 'PROD');

const getEnvValue = (mode, envKey) => {
	const prefixedEnvKey = `${getModePrefix(mode)}_${envKey}`;
	return process.env[prefixedEnvKey] ?? process.env[envKey];
};

const requireEnvValue = (mode, envKey) => {
	const value = getEnvValue(mode, envKey);
	if (!value) {
		throw new Error(
			`Missing required environment variable: ${getModePrefix(mode)}_${envKey} (or ${envKey})`,
		);
	}

	return value;
};

const quoteEnvValue = (value) => JSON.stringify(value);

const buildFunctionsConfig = (mode) => {
	const config = {};

	for (const key of REQUIRED_FUNCTION_ENV_KEYS) {
		config[key] = requireEnvValue(mode, key);
	}

	for (const key of OPTIONAL_FUNCTION_ENV_KEYS) {
		const value = getEnvValue(mode, key);
		if (value !== undefined && value !== '') {
			config[key] = value;
		}
	}

	return config;
};

const renderFunctionsEnvFile = (mode, projectId, config) => {
	const lines = [
		`# This file is auto-generated by config.functions.cjs for ${projectId} (${mode}).`,
		'# Do not edit this file manually.',
		'',
	];

	for (const key of ALL_FUNCTION_ENV_KEYS) {
		const value = config[key];
		if (value === undefined) {
			continue;
		}

		lines.push(`${key}=${quoteEnvValue(value)}`);
	}

	lines.push('');
	return lines.join('\n');
};

const generateFunctionsEnvFile = async (mode) => {
	loadLocalEnvFiles();

	const normalizedMode = parseMode(mode);
	const projectId = FUNCTION_PROJECT_IDS[normalizedMode];
	const targetPath = path.resolve(
		__dirname,
		`santashop-functions/.env.${projectId}`,
	);
	const config = buildFunctionsConfig(normalizedMode);
	const fileContents = renderFunctionsEnvFile(
		normalizedMode,
		projectId,
		config,
	);

	await writeFile(targetPath, fileContents, 'utf8');
	console.log(
		`Generated Functions env file for ${projectId} (${normalizedMode}) at ${targetPath}`,
	);
	return targetPath;
};

const main = async () => {
	await generateFunctionsEnvFile(process.argv[2]);
};

module.exports = {
	FUNCTION_PROJECT_IDS,
	REQUIRED_FUNCTION_ENV_KEYS,
	OPTIONAL_FUNCTION_ENV_KEYS,
	ALL_FUNCTION_ENV_KEYS,
	loadLocalEnvFiles,
	parseMode,
	getModePrefix,
	getEnvValue,
	requireEnvValue,
	quoteEnvValue,
	buildFunctionsConfig,
	renderFunctionsEnvFile,
	generateFunctionsEnvFile,
	main,
};

if (require.main === module) {
	void main().catch((error) => {
		console.error(error);
		process.exitCode = 1;
	});
}
