const { writeFile } = require('node:fs/promises');
const path = require('node:path');
const { loadEnvFiles } = require('./scripts/env-loader.cjs');

const FUNCTION_PROJECT_IDS = {
	local: 'demo-santashop',
	test: 'santas-workshop-test',
	prod: 'santas-workshop-193b5',
};

const REQUIRED_FUNCTION_ENV_KEYS = [
	'AWS_ACCESS_KEY_ID',
	'AWS_SECRET_ACCESS_KEY',
	'SANTASHOP_PROGRAM_YEAR',
	'SANTASHOP_TIME_ZONE',
	'SANTASHOP_TIME_OFFSET',
	'SANTASHOP_DEFAULT_MAX_SLOTS',
	'FIRESTORE_BACKUP_BUCKET',
	'SES_REGION',
	'REGISTRATION_EMAIL_TEMPLATE',
	'REMINDER_EMAIL_TEMPLATE',
	'SANTASHOP_EVENT_DISPLAY_NAME',
	'REGISTRATION_EMAIL_SOURCE',
	'REGISTRATION_EMAIL_RETURN_PATH',
	'SCHEDULED_FIRESTORE_BACKUP',
	'SCHEDULED_DATETIME_SLOT_COUNTERS',
	'SCHEDULED_REGISTRATION_STATS',
	'SCHEDULED_USER_STATS',
	'SCHEDULED_CHECKIN_STATS',
];

const OPTIONAL_FUNCTION_ENV_KEYS = [
	'SANTASHOP_SHOP_DAYS',
	'REMINDER_EMAIL_SENDING_STALE_MINUTES',
	'AWS_REGION',
	'SANTASHOP_SIGNUP_MIN_INSTANCES',
	'SANTASHOP_EVENT_MIN_INSTANCES',
	'SANTASHOP_FUNCTIONS_SERVICE_ACCOUNT',
];

const ALL_FUNCTION_ENV_KEYS = [
	...REQUIRED_FUNCTION_ENV_KEYS,
	...OPTIONAL_FUNCTION_ENV_KEYS,
];

const PLACEHOLDER_AWS_CREDENTIAL_PATTERN =
	/^your-(?:(?:local|test|prod)-)?aws-(?:access-key-id|secret-access-key)$/iu;

const loadLocalEnvFiles = () => {
	loadEnvFiles([
		path.resolve(process.cwd(), '.env'),
		path.resolve(__dirname, '.env'),
	]);
};

const parseMode = (value) => {
	if (value === 'local') {
		return 'local';
	}

	if (!value || value === 'prod' || value === 'production') {
		return 'prod';
	}

	if (
		value === 'test' ||
		value === 'qa' ||
		value === 'dev' ||
		value === 'development'
	) {
		return 'test';
	}

	throw new Error(
		'Expected Functions config mode to be one of: local, test, qa, dev, development, prod, production.',
	);
};

const getModePrefix = (mode) => {
	if (mode === 'local') {
		return 'LOCAL';
	}

	return mode === 'test' ? 'TEST' : 'PROD';
};

const getEnvValue = (mode, envKey) => {
	const prefixedEnvKey = `${getModePrefix(mode)}_${envKey}`;
	return (
		process.env[prefixedEnvKey] ??
		(mode === 'local' ? process.env[`TEST_${envKey}`] : undefined) ??
		process.env[envKey]
	);
};

const requireEnvValue = (mode, envKey) => {
	const value = getEnvValue(mode, envKey);
	if (!value) {
		throw new Error(
			`Missing required environment variable: ${getModePrefix(mode)}_${envKey} (or ${envKey})`,
		);
	}

	return value;
};

const quoteEnvValue = (value) => JSON.stringify(value);

const buildFunctionsConfig = (mode) => {
	const config = {};

	for (const key of REQUIRED_FUNCTION_ENV_KEYS) {
		config[key] = requireEnvValue(mode, key);
	}

	for (const key of OPTIONAL_FUNCTION_ENV_KEYS) {
		const value = getEnvValue(mode, key);
		if (value !== undefined && value !== '') {
			config[key] = value;
		}
	}

	for (const key of ['AWS_ACCESS_KEY_ID', 'AWS_SECRET_ACCESS_KEY']) {
		if (PLACEHOLDER_AWS_CREDENTIAL_PATTERN.test(config[key].trim())) {
			throw new Error(
				`Refusing to use placeholder AWS credential: ${getModePrefix(mode)}_${key} (or ${key})`,
			);
		}
	}

	const programYear = Number.parseInt(config.SANTASHOP_PROGRAM_YEAR, 10);
	if (
		!Number.isInteger(programYear) ||
		programYear < 2000 ||
		programYear > 2100
	) {
		throw new Error(
			'SANTASHOP_PROGRAM_YEAR must be a four-digit year between 2000 and 2100.',
		);
	}

	const eventYearMatch = /\b(?:20\d{2}|2100)\b/u.exec(
		config.SANTASHOP_EVENT_DISPLAY_NAME,
	);
	if (eventYearMatch && Number.parseInt(eventYearMatch[0], 10) !== programYear) {
		throw new Error(
			'SANTASHOP_EVENT_DISPLAY_NAME year must match SANTASHOP_PROGRAM_YEAR.',
		);
	}

	for (const key of [
		'SANTASHOP_SIGNUP_MIN_INSTANCES',
		'SANTASHOP_EVENT_MIN_INSTANCES',
	]) {
		const value = config[key];
		if (value === undefined) continue;
		const parsed = Number.parseInt(value, 10);
		if (!Number.isInteger(parsed) || parsed < 0 || parsed > 10) {
			throw new Error(`${key} must be a whole number between 0 and 10.`);
		}
	}

	return config;
};

const renderFunctionsEnvFile = (mode, projectId, config) => {
	const lines = [
		`# This file is auto-generated by config.functions.cjs for ${projectId} (${mode}).`,
		'# Do not edit this file manually.',
		'',
	];

	for (const key of ALL_FUNCTION_ENV_KEYS) {
		const value = config[key];
		if (value === undefined) {
			continue;
		}

		lines.push(`${key}=${quoteEnvValue(value)}`);
	}

	lines.push('');
	return lines.join('\n');
};

const getGenerationLogMessage = (mode, projectId, targetPath) =>
	`Generated Functions env file for ${projectId} (${mode}) at ${targetPath}`;

const generateFunctionsEnvFile = async (mode) => {
	loadLocalEnvFiles();

	const normalizedMode = parseMode(mode);
	const projectId = FUNCTION_PROJECT_IDS[normalizedMode];
	const targetPath = path.resolve(
		__dirname,
		`santashop-functions/.env.${projectId}`,
	);
	const config = buildFunctionsConfig(normalizedMode);
	const fileContents = renderFunctionsEnvFile(
		normalizedMode,
		projectId,
		config,
	);

	await writeFile(targetPath, fileContents, 'utf8');
	console.log(
		getGenerationLogMessage(normalizedMode, projectId, targetPath),
	);
	return targetPath;
};

const main = async () => {
	await generateFunctionsEnvFile(process.argv[2]);
};

module.exports = {
	FUNCTION_PROJECT_IDS,
	REQUIRED_FUNCTION_ENV_KEYS,
	OPTIONAL_FUNCTION_ENV_KEYS,
	ALL_FUNCTION_ENV_KEYS,
	loadLocalEnvFiles,
	parseMode,
	getModePrefix,
	getEnvValue,
	requireEnvValue,
	quoteEnvValue,
	buildFunctionsConfig,
	renderFunctionsEnvFile,
	getGenerationLogMessage,
	generateFunctionsEnvFile,
	main,
};

if (require.main === module) {
	void main().catch((error) => {
		console.error(error);
		process.exitCode = 1;
	});
}
